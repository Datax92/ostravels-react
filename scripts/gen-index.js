// Writes src/data/menuIndex.generated.js — a tiny list of country names/slugs
// for the nav menus and route table, so the first page load doesn't have to
// download the full country dataset. Runs automatically before dev & build.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { visaCountries } from "../src/data/visaCountries.js";
import { fileProcessingCountries } from "../src/data/fileProcessingCountries.js";
import { countryDirectory } from "../src/data/countryDirectory.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pick = (list) => list.map((c) => ({ slug: c.slug, name: c.name }));

const out = `// AUTO-GENERATED by scripts/gen-index.js — do not edit by hand.
export const visaMenuIndex = ${JSON.stringify(pick(visaCountries))};
export const fileMenuIndex = ${JSON.stringify(pick(fileProcessingCountries))};
export const landingKeys = ${JSON.stringify(countryDirectory.map((c) => c.key))};
`;

fs.writeFileSync(path.join(ROOT, "src/data/menuIndex.generated.js"), out, "utf-8");
console.log(`menuIndex.generated.js: ${visaCountries.length} visa, ${fileProcessingCountries.length} file, ${countryDirectory.length} landing keys`);
